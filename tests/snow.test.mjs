import assert from 'node:assert/strict';
import {snowSettings, snowVolume} from '../web/snow-state.js';
assert.equal(snowSettings('clear',false).count,0);
assert.ok(snowSettings('snow',false).count>0);
assert.ok(snowSettings('snow',true).count>snowSettings('snow',false).count);
assert.equal(snowSettings('bogus',false).count,0);
assert.deepEqual(snowVolume(1),{radius:26,height:32,size:.13});
assert.ok(snowVolume(10000).radius<=500);
assert.ok(snowVolume(10000).size<=1.4);
console.log('snow settings and bounded volume tests pass');
const THREE=await import('three');
const {SnowWeather}=await import('../web/snow-weather.js');
const scene=new THREE.Scene(),camera=new THREE.PerspectiveCamera();
const roof=new THREE.Mesh(new THREE.BoxGeometry(10,1,10),new THREE.MeshBasicMaterial());roof.position.y=5;roof.updateMatrixWorld();
const snow=new SnowWeather({scene,camera,target:()=>new THREE.Vector3(),model:()=>roof});
assert.equal(snow.points.visible,false);
snow.set('snow');assert.equal(snow.geometry.drawRange.count,2400);
snow.update(.016,800);assert.equal(snow.points.visible,false,'roof shelters local snowfall');
camera.position.x=20;snow.update(.5,800);for(let i=0;i<11;i++)snow.update(.05,800);
assert.equal(snow.points.visible,true,'outside roof snow visible');
snow.set('snow',true);assert.equal(snow.geometry.drawRange.count,6000);
snow.set('clear');assert.equal(snow.points.visible,false);assert.equal(snow.geometry.drawRange.count,0);
snow.dispose();assert.equal(scene.children.length,0);
console.log('snow scene lifecycle, quality and roof shielding tests pass');
